"""Opt-in structured indicator announcements with distinct official/consensus provenance.

User- or provider-supplied structured releases are imported, never generated by
the LLM. Consensus is unavailable unless dated independent source evidence
is attached. This adapter does not pretend to be an automatic data vendor.
"""
from __future__ import annotations

import hashlib
import sqlite3
from contextlib import closing
from datetime import datetime
from pathlib import Path
from urllib.parse import urlsplit

from pydantic import BaseModel, ConfigDict, Field, model_validator


class IndicatorRelease(BaseModel):
    model_config = ConfigDict(extra="forbid")
    releaseId: str = Field(min_length=2, max_length=120)
    indicatorName: str = Field(min_length=2, max_length=120)
    period: str = Field(min_length=2, max_length=80)
    publishedAt: datetime
    actual: str = Field(min_length=1, max_length=80)
    previous: str | None = None
    consensus: str | None = None
    actualSourceName: str = Field(min_length=2, max_length=160)
    actualSourceUrl: str
    actualExcerpt: str = Field(min_length=20, max_length=1000)
    consensusPublishedAt: datetime | None = None
    consensusSourceName: str | None = None
    consensusSourceUrl: str | None = None
    consensusExcerpt: str | None = None

    @model_validator(mode="after")
    def source_constraints(self) -> IndicatorRelease:
        if self.publishedAt.tzinfo is None or self.publishedAt.utcoffset() is None:
            raise ValueError("INDICATOR_PUBLICATION_TIME_REQUIRED")
        for address in (self.actualSourceUrl, self.consensusSourceUrl):
            if address is None:
                continue
            parsed = urlsplit(address)
            if (
                parsed.scheme != "https" or not parsed.hostname
                or parsed.username or parsed.password
                or parsed.fragment or parsed.port not in (None, 443)
            ):
                raise ValueError("INDICATOR_SOURCE_INVALID")
        if self.actual not in self.actualExcerpt:
            raise ValueError("INDICATOR_ACTUAL_NOT_IN_SOURCE")
        if self.previous is not None and self.previous not in self.actualExcerpt:
            raise ValueError("INDICATOR_PREVIOUS_NOT_IN_SOURCE")
        meta = (
            self.consensusPublishedAt, self.consensusSourceName,
            self.consensusSourceUrl, self.consensusExcerpt,
        )
        if self.consensus is None:
            if any(item is not None for item in meta):
                raise ValueError("INDICATOR_CONSENSUS_INCOMPLETE")
        elif (
            any(item is None for item in meta)
            or self.consensus not in (self.consensusExcerpt or "")
            or self.consensusPublishedAt >= self.publishedAt
        ):
            raise ValueError("INDICATOR_CONSENSUS_NOT_PRE_RELEASE_OR_UNSOURCED")
        return self


class IndicatorReleaseBatch(BaseModel):
    model_config = ConfigDict(extra="forbid")
    schemaVersion: str = "market_indicator_release_batch_v1"
    releases: list[IndicatorRelease] = Field(min_length=1, max_length=100)

    @model_validator(mode="after")
    def unique_releases(self) -> IndicatorReleaseBatch:
        if self.schemaVersion != "market_indicator_release_batch_v1":
            raise ValueError("INDICATOR_BATCH_VERSION_UNSUPPORTED")
        ids = [item.releaseId for item in self.releases]
        if len(ids) != len(set(ids)):
            raise ValueError("INDICATOR_RELEASE_IDS_DUPLICATED")
        return self


class IndicatorReleaseStore:
    def __init__(self, path: Path) -> None:
        self.path = path

    def _connect(self, *, readonly: bool = False) -> sqlite3.Connection:
        if self.path.is_symlink() or not self.path.is_file():
            raise ValueError("EXISTING_NEWS_DB_REQUIRED")
        db = sqlite3.connect(
            self.path.resolve().as_uri() + ("?mode=ro" if readonly else "?mode=rw"),
            uri=True, timeout=10,
        )
        if readonly:
            db.execute("PRAGMA query_only=ON")
        return db

    def initialize(self) -> None:
        with closing(self._connect()) as db, db:
            db.execute("""CREATE TABLE IF NOT EXISTS market_indicator_releases (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                release_id TEXT NOT NULL UNIQUE,
                published_at TEXT NOT NULL,
                payload_json TEXT NOT NULL,
                payload_sha256 TEXT NOT NULL
            )""")
            db.execute("""CREATE INDEX IF NOT EXISTS
                idx_market_indicator_releases_published
                ON market_indicator_releases(published_at)""")

    def import_batch(self, batch: IndicatorReleaseBatch) -> dict:
        batch = IndicatorReleaseBatch.model_validate(batch)
        saved = unchanged = 0
        with closing(self._connect()) as db, db:
            for item in batch.releases:
                raw = item.model_dump_json()
                digest = hashlib.sha256(raw.encode()).hexdigest()
                row = db.execute(
                    """SELECT payload_sha256 FROM market_indicator_releases
                       WHERE release_id=?""", (item.releaseId,),
                ).fetchone()
                if row is not None:
                    if row[0] != digest:
                        raise ValueError("INDICATOR_RELEASE_IMMUTABLE_CONFLICT")
                    unchanged += 1
                    continue
                db.execute(
                    """INSERT INTO market_indicator_releases
                       (release_id, published_at, payload_json, payload_sha256)
                       VALUES (?, ?, ?, ?)""",
                    (item.releaseId, item.publishedAt.isoformat(), raw, digest),
                )
                saved += 1
        return {"inserted": saved, "unchanged": unchanged}

    def read(self, index: int) -> IndicatorRelease:
        if type(index) is not int or index <= 0:
            raise ValueError("INDICATOR_RELEASE_INDEX_INVALID")
        with closing(self._connect(readonly=True)) as db:
            row = db.execute(
                """SELECT payload_json, payload_sha256
                   FROM market_indicator_releases WHERE id=?""", (index,),
            ).fetchone()
        if row is None:
            raise ValueError("INDICATOR_RELEASE_NOT_FOUND")
        raw, checksum = row
        if hashlib.sha256(raw.encode()).hexdigest() != checksum:
            raise ValueError("INDICATOR_RELEASE_CHECKSUM_INVALID")
        return IndicatorRelease.model_validate_json(raw)
